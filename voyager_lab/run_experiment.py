"""One official three-arm evaluation.

Refuses to start when the rubric lock is missing or mismatched.
Refuses to start when results/summary.json already exists.
Does not edit the suite, the rubric, or the controllers.
"""

import json
import sys
from pathlib import Path

from freeze import verify
from voyager.atomic import atomic_write
from voyager.harness import run_arm
from voyager.rubric import compare, lesson_flags, summarize

LAB_ROOT = Path(__file__).resolve().parent
RESULTS = LAB_ROOT / "results"
SUMMARY = RESULTS / "summary.json"

ARMS = (
    ("baseline", "baseline", False),
    ("engine", "engine", True),
    ("ablation", "engine", False),
)


def _jsonl(rows) -> str:
    return "".join(json.dumps(row, sort_keys=True) + "\n" for row in rows)


def _results_md(report) -> str:
    lines = [
        "# Voyager official results",
        "",
        "Generated by run_experiment.py from results/summary.json.",
        "The external file check is the objective. A success string is not a pass.",
        f"Rubric bundle: {report['rubric_bundle_sha256']}",
        "",
        "## Aggregates",
        "",
        "| metric | baseline | engine | ablation |",
        "| --- | ---: | ---: | ---: |",
    ]
    comparison = report["comparison"]
    for key in (
        "completion_rate",
        "successful_recovery_rate",
        "unsupported_completion_claims",
        "contradictions",
        "repeated_failed_operations",
        "resource_tool_calls",
        "resource_elapsed_ms",
        "recovery_after_restart_rate",
        "blocked_when_should_block_rate",
        "unfamiliar_rate",
    ):
        item = comparison[key]
        lines.append(
            f"| {key} | {item['baseline']} | {item['engine']} | {report['ablation'].get(key, '')} |"
        )
    lines.extend(
        [
            "",
            f"Ablation completion rate: {comparison['ablation_completion_rate']}",
            f"Engine completion rate: {comparison['engine_completion_rate']}",
            "",
            "## Policy non-repeat (M24 stays inside completion_rate)",
            "",
        ]
    )
    for name in ("baseline", "engine", "ablation"):
        policy = report[name]["policy_non_repeat"]
        lines.append(
            f"- {name}: pass={policy['objective_pass']} status={policy['status']} "
            f"unsupported={policy['unsupported']} repeat_extras={policy['repeat_extras']}"
        )
    lines.extend(["", "## Lesson flags", ""])
    if not report["lesson_flags"]:
        lines.append("None.")
    else:
        for item in report["lesson_flags"]:
            lines.append("- " + json.dumps(item, sort_keys=True))
    lines.extend(["", "## Per mission", ""])
    lines.append("| id | baseline pass | engine pass | ablation pass | engine status | engine learning |")
    lines.append("| --- | --- | --- | --- | --- | --- |")
    by_arm = {}
    for name in ("baseline", "engine", "ablation"):
        by_arm[name] = {row["mission_id"]: row for row in report["rows"][name]}
    ids = [row["mission_id"] for row in report["rows"]["baseline"]]
    for mission_id in ids:
        base = by_arm["baseline"][mission_id]
        engine = by_arm["engine"][mission_id]
        ablation = by_arm["ablation"][mission_id]
        lines.append(
            f"| {mission_id} | {base['objective_pass']} | {engine['objective_pass']} | "
            f"{ablation['objective_pass']} | {engine['status']} | {engine['learning_applied']} |"
        )
    lines.append("")
    return "\n".join(lines)


def main(argv) -> int:
    if "--run" not in argv:
        print("pass --run to execute the one official evaluation")
        return 2
    locked = verify()
    if SUMMARY.exists() or (RESULTS / "raw").exists():
        raise SystemExit("results already exist; refuse a second official run")
    rows_by = {}
    summaries = {}
    for label, controller, lessons_enabled in ARMS:
        rows = run_arm(
            controller,
            RESULTS / "raw" / label,
            lessons_enabled=lessons_enabled,
            label=label,
        )
        rows_by[label] = rows
        atomic_write(str(RESULTS / f"{label}.jsonl"), _jsonl(rows))
        summaries[label] = summarize(label, rows)
    report = {
        "rubric_bundle_sha256": locked["bundle_sha256"],
        "baseline": summaries["baseline"],
        "engine": summaries["engine"],
        "ablation": summaries["ablation"],
        "comparison": compare(summaries["baseline"], summaries["engine"], summaries["ablation"]),
        "lesson_flags": lesson_flags(rows_by["engine"], rows_by["ablation"]),
        "rows": rows_by,
    }
    atomic_write(str(SUMMARY), json.dumps(report, indent=2, sort_keys=True) + "\n")
    atomic_write(str(RESULTS / "RESULTS.md"), _results_md(report))
    print("OFFICIAL_RUN_DONE")
    print(json.dumps(report["comparison"], indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
