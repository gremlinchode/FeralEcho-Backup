"""Task manifest: formalizes the base task families, paired w0/w1
micro-worlds, teaching/withheld/near-match/unrelated query pools, and the
non-duplication standard for "genuinely withheld related transfer task."

Builds directly on two prior artifacts rather than reinventing them:

  1. `schema.MicroWorldSpec` (already implemented, already exercised by
     52/52 tests) - reused here verbatim as the per-world fixture shape,
     not redefined.
  2. The non-duplication standard from
     audits/2026-09-16_e5_mini_adversarial_preimplementation_review.md
     §6: "a withheld task is genuinely novel and requires the taught
     method only if (a) it fails all mechanical duplication checks
     (hash/lexical/AST/I-O), AND (b) a blind solver given only the
     unrelated-task pool (never the family's teaching content or the
     family label) fails it at a materially higher rate than a solver
     given the teaching content - i.e., novelty is defined empirically,
     by a difficulty differential under blinding, not by any static
     structural comparison alone."

Also encodes the §8 MUST-FIX rule from that same review: "pre-register
the full family list and forbid post hoc family exclusion" - the
manifest structurally cannot represent a family being silently dropped
after freezing (see `TaskManifest.frozen_family_ids` and
`assert_no_family_removed`).

DESIGN ARTIFACT ONLY. No real scientific task content is generated by
this module - `EXAMPLE_SYNTHETIC_MANIFEST` at the bottom is explicitly
sacrificial fixture data, same status as `mock.py`'s `RECIPE_CLASSES`.
"""
from __future__ import annotations

import dataclasses
from dataclasses import dataclass, field

from ..schema import MicroWorldSpec, sha256_of, unknown


def _full_manifest_content_hash(protocol_id: str, families: "list", min_difficulty_gap_required: float,
                                 custodian_process_id: str) -> str:
    """Hashes the FULL content of every family (world specs, novelty
    records included) via dataclasses.asdict(), not just family_ids.
    Hashing only family_ids (the first draft of this module's freeze()
    did exactly that) would let a family's INTERNAL content - e.g. a
    forged passing QueryNoveltyRecord snuck into an already-frozen
    family's related_query_novelty list - be tampered with completely
    undetected, since the id set alone never changes. Found and fixed
    during this mission's own hostile review (finding TASK-1)."""
    return sha256_of({
        "protocol_id": protocol_id,
        "families": [dataclasses.asdict(f) for f in sorted(families, key=lambda f: f.family_id)],
        "min_difficulty_gap_required": min_difficulty_gap_required,
        "custodian_process_id": custodian_process_id,
    })


@dataclass
class MechanicalDuplicationCheck:
    """Result of the static, structural half of the non-duplication
    standard (review §6 part (a)). All four sub-checks are required;
    ANY hit means the withheld task fails novelty regardless of the
    blind-solver differential in `NoveltyEvidence` below."""
    query_id: str
    exact_hash_match: bool  # True = FAIL (identical to a teaching example)
    lexical_similarity_score: float  # 0.0-1.0, normalized; threshold is a manifest-level constant, not per-task
    ast_or_control_flow_identical: bool  # True on a structural match even under renamed symbols/reordered input
    io_structure_identical: bool  # same input/output shape as a teaching example, independent of surface text
    reviewer_note: str  # human/custodian free-text - never the sole basis for a pass, only supplementary


@dataclass
class NoveltyEvidence:
    """The empirical half (review §6 part (b)) - the only part of the
    standard that is actually falsifiable rather than asserted. Both
    solver conditions below must use the SAME frozen model/backend and
    SAME solve budget as the real E5-mini run's N arm, or this evidence
    is not comparable to the real result it's meant to validate."""
    query_id: str
    blind_zero_context_attempts: int  # solver given ONLY the unrelated-task pool, never this family's teaching/label
    blind_zero_context_successes: int
    teaching_informed_attempts: int  # solver given this family's real teaching content (same as N would NOT get, P/E would)
    teaching_informed_successes: int

    @property
    def blind_success_rate(self) -> float:
        return self.blind_zero_context_successes / self.blind_zero_context_attempts if self.blind_zero_context_attempts else 0.0

    @property
    def informed_success_rate(self) -> float:
        return self.teaching_informed_successes / self.teaching_informed_attempts if self.teaching_informed_attempts else 0.0

    def passes_difficulty_differential(self, min_gap: float) -> bool:
        """review §6: novelty requires informed success rate to exceed
        blind success rate by at least `min_gap` - a task that's equally
        hard either way was never testing the taught method specifically."""
        return (self.informed_success_rate - self.blind_success_rate) >= min_gap


@dataclass
class QueryNoveltyRecord:
    """One withheld/related query's complete non-duplication dossier -
    both halves of the standard, plus the final pass/fail this manifest
    freezes. A query with no QueryNoveltyRecord is not eligible to be
    used as a scored 'related' query under this manifest (see
    `TaskManifest.unvalidated_related_queries`)."""
    query_id: str
    mechanical: MechanicalDuplicationCheck
    novelty: NoveltyEvidence
    min_difficulty_gap: float  # the frozen threshold this record was validated against
    passed: bool  # frozen at manifest-freeze time; NOT re-derived live by any consumer


@dataclass
class FamilyManifestEntry:
    family_id: str
    w0: MicroWorldSpec
    w1: MicroWorldSpec
    related_query_novelty: "list[QueryNoveltyRecord]"  # must cover every id in w0.related_queries/w1.related_queries
    family_description_leak_checked: bool  # review §6 item 2: does the family_id/description itself state the method?
    family_description_leak_note: str


@dataclass
class TaskManifest:
    """The frozen, pre-registered family list. Once `freeze()` is
    called, `families` is immutable in spirit (Python cannot enforce
    this at the language level for a plain list - see the hostile
    review's TASK-1 finding for why this matters and what closes the
    gap) and `frozen_family_ids` becomes the enforced membership."""
    protocol_id: str
    families: "list[FamilyManifestEntry]"
    min_difficulty_gap_required: float  # frozen threshold, e.g. 0.30 - applied to EVERY QueryNoveltyRecord at freeze time
    custodian_process_id: str  # WHO/WHAT generated this manifest - unknown(...) if not yet resolved, never fabricated
    frozen_at: "str | None" = None
    frozen_family_ids: "frozenset | None" = None
    manifest_hash: "str | None" = None

    def unvalidated_related_queries(self) -> "list[tuple[str, str]]":
        """(family_id, query_id) pairs used as 'related' in a MicroWorldSpec
        but missing a QueryNoveltyRecord, OR present but recorded as
        passed=False. Non-empty return value means this manifest is NOT
        eligible to freeze."""
        bad: "list[tuple[str, str]]" = []
        for fam in self.families:
            validated_ids = {r.query_id: r.passed for r in fam.related_query_novelty}
            for world in (fam.w0, fam.w1):
                for q in world.related_queries:
                    qid = q["query_id"]
                    if qid not in validated_ids or not validated_ids[qid]:
                        bad.append((fam.family_id, qid))
        return bad

    def freeze(self) -> None:
        # FIXED (confirmed finding #8a): an empty families list froze
        # successfully, because unvalidated_related_queries() iterates
        # self.families and an empty list trivially produces zero
        # failures - "nothing to validate" was silently accepted as "all
        # validated." A manifest with zero families cannot be a real
        # frozen task manifest under any interpretation.
        if not self.families:
            raise ValueError("cannot freeze: manifest has zero families - an empty manifest is not a valid frozen task manifest")
        bad = self.unvalidated_related_queries()
        if bad:
            raise ValueError(f"cannot freeze: {len(bad)} related queries lack a passing novelty record: {bad}")
        if self.frozen_at is not None:
            raise ValueError("manifest already frozen - freezing twice is itself a violation (would let a second freeze silently redefine 'frozen')")
        import datetime
        self.frozen_at = datetime.datetime.now(datetime.timezone.utc).isoformat()
        self.frozen_family_ids = frozenset(f.family_id for f in self.families)
        self.manifest_hash = _full_manifest_content_hash(
            self.protocol_id, self.families, self.min_difficulty_gap_required, self.custodian_process_id)

    def verify_not_tampered(self) -> bool:
        """Recomputes the manifest hash from CURRENT content and compares
        against the value captured at freeze() time. Closes a real gap
        found during hostile review (TASK-1): freeze() only ever captured
        a snapshot hash - nothing re-checked it, so a caller mutating
        `families` after freezing (e.g. appending a fake passing
        QueryNoveltyRecord to sneak a duplicate task past
        unvalidated_related_queries()) went completely undetected. This
        must be called before trusting ANY frozen manifest for analysis."""
        if self.frozen_at is None or self.manifest_hash is None:
            raise ValueError("manifest was never frozen - nothing to verify against")
        current_hash = _full_manifest_content_hash(
            self.protocol_id, self.families, self.min_difficulty_gap_required, self.custodian_process_id)
        return current_hash == self.manifest_hash

    def assert_no_family_removed(self, family_ids_actually_analyzed: "set[str]") -> None:
        """Call this at analysis/reporting time. Raises if the analyzed
        set is a STRICT SUBSET of the frozen set - i.e. some family was
        silently dropped after freezing (review §8's MUST FIX). Adding
        an unfrozen family at analysis time is a DIFFERENT, also-forbidden
        violation, caught separately below."""
        if self.frozen_family_ids is None:
            raise ValueError("manifest was never frozen - nothing to check post hoc exclusion against")
        missing = self.frozen_family_ids - family_ids_actually_analyzed
        if missing:
            raise ValueError(f"POST HOC FAMILY EXCLUSION DETECTED: frozen families {sorted(missing)} are absent from the analyzed set")
        extra = family_ids_actually_analyzed - self.frozen_family_ids
        if extra:
            raise ValueError(f"UNFROZEN FAMILY IN ANALYSIS: {sorted(extra)} were never part of the frozen manifest")
