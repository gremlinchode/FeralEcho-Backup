"""
Outcome-statement template generator (protocol §7, confound-matrix row
"Experimenter bias in outcome-statement wording", §9). All three
non-CONTROL conditions' injected text is generated by this ONE function
from the SAME real objective_verify()-shaped dict, differing only in
which result is substituted — never hand-authored per trial. This is
what makes the True/Sham-reversed comparison (§11, criterion 2) a real
test of truth-sensitivity rather than a test of "which condition
happened to get better-written prose."

Non-imperative by construction (protocol §7's requirement, distinguishing
H1 from H0b/instruction-following) — every template states a fact, never
a directive ("avoid X" / "use X").
"""
from __future__ import annotations

from app.experiments.raoc.schema import Approach, VerifiedOutcome


def _approach_phrase(approach: Approach) -> str:
    return {
        Approach.RECURSIVE: "an approach using recursion",
        Approach.ITERATIVE: "an approach using an explicit loop",
        Approach.UNKNOWN: "one approach",
    }[approach]


def build_outcome_statement(outcome: VerifiedOutcome, *, reversed_valence: bool = False) -> str:
    """
    True-outcome condition: reversed_valence=False, uses the real
    outcome.passed value as-is.

    Sham-outcome (reversed valence) condition: reversed_valence=True —
    same approach description, same category, but the stated pass/fail
    is deliberately flipped from what objective_verify() actually found.
    This function is the ONLY place that flip happens; it never mutates
    the real VerifiedOutcome object itself, so the ground truth stays
    intact for scoring.
    """
    passed = (not outcome.passed) if reversed_valence else outcome.passed
    phrase = _approach_phrase(outcome.approach)
    if passed:
        return (
            f"On a related {outcome.category.replace('_', ' ')} task, "
            f"{phrase} passed all tests."
        )
    reason = outcome.reason.strip() if outcome.reason else "it did not pass all tests"
    return (
        f"On a related {outcome.category.replace('_', ' ')} task, "
        f"{phrase} failed — {reason}."
    )


def build_irrelevant_sham_statement(outcome: VerifiedOutcome) -> str:
    """
    Sham-outcome (irrelevant) condition (protocol §7, §9): same length/
    format as build_outcome_statement()'s output, about a genuinely
    unrelated category, so the comparison isolates topical relevance
    from pure length/format effects. Deliberately reuses the exact same
    template function (with a synthetic, clearly-labeled unrelated
    VerifiedOutcome) rather than a separately hand-written sentence, for
    the same reason real outcome statements aren't hand-authored.
    """
    filler = VerifiedOutcome(
        task_id="__irrelevant_filler__",
        category="string_formatting",
        approach=Approach.ITERATIVE,
        passed=True,
        reason="",
        source="synthetic_filler",
    )
    if filler.category == outcome.category:
        # Extremely unlikely given the fixed filler category, but never
        # silently produce a "relevant" sham — fail loudly instead.
        raise ValueError(
            "Irrelevant-sham filler category collided with the real outcome's "
            "category — this condition must never accidentally become relevant."
        )
    return build_outcome_statement(filler, reversed_valence=False)
