"""
CALIBRATION-ONLY task family: "extract_code" -- fresh, non-contaminated
instances built to reproduce the GENERAL DIFFICULTY STRUCTURE this project's
own real, historical self-edit `prose_stripping` family exhibited (per
CLAUDE.md's Findings 32/43 and this project's own real, live
self_edit_convergence.json/SELF_EDIT.log records), never its literal
content:

  Real historical task (never reused literally here): "strip any leading
  natural-language sentence before the first valid Python token" -- a
  self-edit-specific, Python-syntax-specific, single-purpose transform.

  General difficulty structure extracted from the evidence (Phase 2 of the
  governing mission), NOT the literal wording above: (a) precise BOUNDARY
  DETECTION between unstructured natural-language content and a structured,
  syntactically-valid payload: (b) ROBUSTNESS TO DISTRACTORS -- content that
  superficially resembles the structured payload's own vocabulary but is not
  actually part of it; (c) COMPLETENESS under composition -- a solution that
  works on the easy case can still silently fail once the boundary or the
  payload itself becomes more compositionally complex (multiple boundaries,
  leading AND trailing noise, decorators/docstrings before the "real" code).

This module builds fresh instances of a task with the SAME three difficulty
components, in a domain (a Python code payload wrapped in unrelated prose)
close enough to be a faithful structural analogue but literally
non-identical to the real historical family, at four pre-declared,
monotonically increasing difficulty levels (declared BEFORE any model call
is made, per the governing mission's own explicit no-adaptive-search rule).
"""
from __future__ import annotations

import hashlib
import json
import random

# ---------------------------------------------------------------------------
# Content banks -- small, fixed, human-authored (not generated by any model),
# combined via seeded random choice into fresh instances. None of this text
# is drawn from FeralEcho's own real prose_stripping self-edit history --
# authored fresh for this calibration.
# ---------------------------------------------------------------------------

PLAIN_PROSE_LINES = [
    "Sure, here is a possible approach to the problem you described.",
    "I thought about a few different ways to do this before settling on one.",
    "Let me know if this does not match what you were looking for.",
    "This should cover the case you mentioned, but let me explain first.",
    "Below is my attempt, with a short explanation of the reasoning.",
    "I want to walk through my thinking before showing the final answer.",
    "Here's what I came up with after considering the requirements.",
    "This took a couple of tries to get right, so let me explain.",
]

# Lines that SUPERFICIALLY resemble code vocabulary (contain words a naive
# keyword-matching heuristic might mistake for the start of real code) while
# remaining ordinary, grammatical natural-language sentences.
DISTRACTOR_PROSE_LINES = [
    "You should always define your goals clearly before you begin.",
    "The class of problems here returns to a familiar pattern we've seen before.",
    "Note that this import of new ideas often takes practice to get comfortable with.",
    "A good plan will yield better results than rushing ahead.",
    "Remember that every function of a good design starts with clear intent.",
    "The self-review process is where most people catch their own mistakes.",
]

TRAILING_PROSE_LINES = [
    "I hope that helps -- let me know if you'd like any changes.",
    "Feel free to adapt this to your exact use case.",
    "That should be everything you need for now.",
    "Let me know if any part of this needs further explanation.",
]

# A small bank of real, syntactically valid, self-contained Python code
# snippets, each pre-labeled with whether it opens with a decorator/
# docstring (harder boundary) or a bare `def`/`import` (easier boundary).
CODE_SNIPPETS_SIMPLE = [
    "def add(a, b):\n    return a + b",
    "def is_even(n):\n    return n % 2 == 0",
    "def greet(name):\n    return f\"Hello, {name}!\"",
    "def square(x):\n    return x * x",
]

CODE_SNIPPETS_COMPLEX = [
    "import math\n\n\ndef circle_area(r):\n    return math.pi * r * r",
    "@staticmethod\ndef double(x):\n    return x * 2",
    "\"\"\"Utility function.\"\"\"\ndef triple(x):\n    return x * 3",
    "from functools import lru_cache\n\n\n@lru_cache\ndef fib(n):\n    return n if n < 2 else fib(n - 1) + fib(n - 2)",
]


def _build_instance(rng: random.Random, level: int) -> dict:
    n_plain = rng.randint(1, 2)
    plain_lines = rng.sample(PLAIN_PROSE_LINES, n_plain)
    prose_lines = list(plain_lines)

    if level >= 2:
        n_distractor = 1 if level == 2 else rng.randint(2, 3)
        distractor_lines = rng.sample(DISTRACTOR_PROSE_LINES, min(n_distractor, len(DISTRACTOR_PROSE_LINES)))
        # Interleave distractors among the plain lines rather than always
        # appending them at a fixed position, so position alone is not a
        # reliable cue.
        combined = prose_lines + distractor_lines
        rng.shuffle(combined)
        prose_lines = combined

    leading_prose = "\n".join(prose_lines)

    if level <= 2:
        code = rng.choice(CODE_SNIPPETS_SIMPLE)
    else:
        code = rng.choice(CODE_SNIPPETS_COMPLEX)

    # Level 1-2: single leading blank-line separator. Level 3+: a variable
    # number of blank lines, to prevent a solution from hardcoding "the
    # boundary is always exactly two newlines away."
    n_blank = 1 if level <= 2 else rng.randint(1, 3)
    separator = "\n" * n_blank

    text = leading_prose + separator + code

    trailing = ""
    if level >= 4:
        n_trailing = rng.randint(1, 2)
        trailing_lines = rng.sample(TRAILING_PROSE_LINES, n_trailing)
        trailing = "\n" + "\n".join(trailing_lines)
        text = text + trailing

    return {
        "text": text,
        "expected_code": code,
        "level": level,
        "has_trailing_prose": bool(trailing),
    }


def build_calibration_set(seeds: "list[int]", level: int, prefix: str) -> "list[dict]":
    out = []
    for i, seed in enumerate(seeds):
        rng = random.Random(seed)
        inst = _build_instance(rng, level)
        task_id = f"{prefix}L{level}_{i:02d}"
        description = (
            "You will be given a string `text` that begins with one or more lines "
            "of ordinary natural-language commentary, followed by a valid, "
            "self-contained Python code snippet. "
            + ("Some of the commentary may mention words that sound code-related "
               "(like \"define\", \"class\", \"import\", \"function\", or \"return\") "
               "even though those lines are just ordinary sentences, not code. "
               if level >= 2 else "")
            + ("The code snippet itself may begin with a decorator, a docstring, or "
               "an import statement rather than directly with `def`. "
               if level >= 3 else "")
            + ("After the code snippet, there may also be one or more lines of "
               "trailing natural-language commentary that come AFTER the code and "
               "are not part of it. "
               if level >= 4 else "")
            + "Write a function that returns ONLY the exact Python code portion of "
              "`text` -- excluding any leading commentary"
            + (" and excluding any trailing commentary" if level >= 4 else "")
            + " -- as a string, with no other text added or removed."
        )
        out.append({
            "task_id": task_id,
            "level": level,
            "seed": seed,
            "description": description,
            "text": inst["text"],
            "expected_code": inst["expected_code"],
        })
    return out


def canonical_json(obj) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"))


def sha256_of(obj) -> str:
    return hashlib.sha256(canonical_json(obj).encode("utf-8")).hexdigest()


if __name__ == "__main__":
    # Self-check: every level's instances have `expected_code` genuinely
    # appearing inside `text` exactly once, at the position construction
    # implies (not merely "somewhere" -- the whole point is a well-defined
    # boundary), across a range of seeds. This is the calibration-only
    # module's own reference-correctness guarantee (there is no separate
    # "reference solver" to test here -- correctness is true by
    # construction, since the harness builds `text` from `expected_code`
    # rather than parsing it back out -- but this self-check independently
    # re-derives the same fact via a naive substring search, as a real,
    # non-trivial cross-check rather than a tautology).
    for level in (1, 2, 3, 4):
        insts = build_calibration_set(list(range(500, 510)), level, "selfcheck_")
        for inst in insts:
            assert inst["text"].count(inst["expected_code"]) == 1, (
                f"level={level} task={inst['task_id']}: expected_code does not "
                f"appear exactly once in text"
            )
    print("tasks.py self-check: OK (40/40 instances across levels 1-4 have a "
          "well-defined, unique code boundary)")
